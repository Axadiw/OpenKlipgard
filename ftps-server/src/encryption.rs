use base64::{engine::general_purpose::URL_SAFE_NO_PAD, Engine as _};
use hkdf::Hkdf;
use sha2::Sha256;

/// HKDF info of SSE-C key generation 1, byte-identical to `SSE_C_KDF_INFO` in
/// `server/services/encryption.ts`. Part of the stored-data format: never change it.
const SSE_C_KDF_INFO: &[u8] = &[0x63, 0x6c, 0x69, 0x70, 0x6e, 0x65, 0x73, 0x74, 0x2d, 0x73, 0x73, 0x65, 0x2d, 0x63, 0x2d, 0x76, 0x31];

/// HKDF info of SSE-C key generation 2, byte-identical to `SSE_C_KDF_INFO_V2`
/// in `server/services/encryption.ts`. Part of the stored-data format too.
const SSE_C_KDF_INFO_V2: &[u8] = b"klipgard-sse-c-v2";

/// SSE-C key generation of a bucket (spec DATA-102, DATA-146). The generation
/// is a pure function of the bucket name: `KLIPGARD_SSE_V2_BUCKETS` lists the
/// generation-2 buckets, every other bucket is generation 1.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum KeyGeneration {
    /// The original derivation. Every object written before generation 2 existed uses it.
    V1,
    /// Own HKDF info, and the own master key `KLIPGARD_ENCRYPTION_MASTER_KEY_V2` when set.
    V2,
}

impl KeyGeneration {
    pub fn as_number(self) -> u8 {
        match self {
            Self::V1 => 1,
            Self::V2 => 2,
        }
    }
}

/// The generation of the objects in `bucket`: V2 if the bucket is listed
/// (exact match), else V1. Same rule as `keyGenerationForBucket` in Node.
pub fn key_generation_for_bucket(bucket: &str, v2_buckets: &[String]) -> KeyGeneration {
    if v2_buckets.iter().any(|b| b == bucket) {
        KeyGeneration::V2
    } else {
        KeyGeneration::V1
    }
}

/// The master key of a generation. Generation 2 falls back to the
/// generation-1 key when no own key is set (`None` or empty).
pub fn master_key_for_generation<'a>(
    generation: KeyGeneration,
    master_key: &'a str,
    master_key_v2: Option<&'a str>,
) -> &'a str {
    match (generation, master_key_v2) {
        (KeyGeneration::V2, Some(v2)) if !v2.is_empty() => v2,
        _ => master_key,
    }
}

/// Derive a 32-byte SSE-C encryption key for a user using HKDF-SHA256.
///
/// Must produce identical output to the Node.js implementation
/// (`deriveUserKey` in `server/services/encryption.ts`):
/// ```js
/// const ikm = Buffer.from(masterKey, 'utf-8');
/// const salt = Buffer.from(userSalt, 'base64url');
/// const info = generation === 2 ? Buffer.from('klipgard-sse-c-v2', 'utf-8')
///   : Buffer.from('636c69706e6573742d7373652d632d7631', 'hex');
/// const derived = crypto.hkdfSync('sha256', ikm, salt, info, 32);
/// ```
/// `generation` only picks the HKDF info. The caller passes the master key of
/// that generation (`master_key_for_generation`).
pub fn derive_user_key(master_key: &str, user_salt: &str, generation: KeyGeneration) -> [u8; 32] {
    let ikm = master_key.as_bytes();
    let salt = URL_SAFE_NO_PAD
        .decode(user_salt)
        .expect("invalid base64url salt");
    let info = match generation {
        KeyGeneration::V1 => SSE_C_KDF_INFO,
        KeyGeneration::V2 => SSE_C_KDF_INFO_V2,
    };

    let hkdf = Hkdf::<Sha256>::new(Some(&salt), ikm);
    let mut okm = [0u8; 32];
    hkdf.expand(info, &mut okm).expect("HKDF expand failed");
    okm
}

/// Compute SSE-C header values for S3 operations.
///
/// Returns (algorithm, key_base64, key_md5_base64).
pub fn ssec_headers(key: &[u8; 32]) -> (String, String, String) {
    use base64::engine::general_purpose::STANDARD;
    use md5::{Digest, Md5};

    let algorithm = "AES256".to_string();
    let key_b64 = STANDARD.encode(key);
    let mut hasher = Md5::new();
    hasher.update(key);
    let key_md5 = STANDARD.encode(hasher.finalize());
    (algorithm, key_b64, key_md5)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(key: &[u8; 32]) -> String {
        key.iter().map(|b| format!("{:02x}", b)).collect::<String>()
    }

    ///story: Klucze per-user wyprowadzone HKDF-SHA256 są bitowo zgodne z wersją Node — gwarancja, że plik zaszyfrowany przez FTPS da się odszyfrować przez API.
    #[test]
    fn test_derive_user_key_matches_nodejs() {
        // Reference value generated by Node.js:
        // node -e "const c = require('crypto');
        //   const key = Buffer.from(c.hkdfSync('sha256', 'testkey',
        //     Buffer.from('dGVzdHNhbHQ', 'base64url'),
        //     Buffer.from('636c69706e6573742d7373652d632d7631', 'hex'), 32));
        //   console.log(key.toString('hex'))"
        // Output: d1ffb4baebfbfcbd72477c9779c30efce44c565ecfd0b38c0a0dde7bcc9f6b6b
        let key = derive_user_key("testkey", "dGVzdHNhbHQ", KeyGeneration::V1);
        assert_eq!(
            hex(&key), "d1ffb4baebfbfcbd72477c9779c30efce44c565ecfd0b38c0a0dde7bcc9f6b6b",
            "HKDF output must match Node.js reference"
        );
    }

    ///story: [DATA-102] Generacja 1 to bajt w bajt dotychczasowe wyprowadzenie klucza — ten sam wektor sprawdza `encryption.test.ts` w Node. Gdyby się zmienił, żaden istniejący obiekt nie dałby się odczytać.
    #[test]
    fn generation_1_matches_the_fixed_node_vector() {
        let key = derive_user_key(
            "klipgard-test-master-key-0123456789abcdef",
            "Zml4ZWQtc2FsdC1mb3ItdGhlLWtub3duLXZlY3Rvcg",
            KeyGeneration::V1,
        );
        assert_eq!(hex(&key), "a45c5bd43c73c92c2fb410f5eae48b366f4bd1583391fba69dded53f4be9728a");
        let (_, _, md5) = ssec_headers(&key);
        assert_eq!(md5, "X0s/K87M+2N0JGhwnP9iJQ==");
    }

    ///story: [DATA-146] Generacja 2 (info `klipgard-sse-c-v2`) daje w Rust ten sam klucz co w Node — nagranie wgrane przez FTPS do bucketu generacji 2 da się odtworzyć przez API.
    #[test]
    fn generation_2_matches_the_node_vectors() {
        let key = derive_user_key(
            "klipgard-test-master-key-0123456789abcdef",
            "Zml4ZWQtc2FsdC1mb3ItdGhlLWtub3duLXZlY3Rvcg",
            KeyGeneration::V2,
        );
        assert_eq!(hex(&key), "7bdfd2c6c6dbf23763b7abb2a0718d5669602a56d7ba1cc80b7ca392a8a34403");
        let (_, _, md5) = ssec_headers(&key);
        assert_eq!(md5, "wxBF2et9TLlzDZwiywCt0w==");
        assert_eq!(
            hex(&derive_user_key("testkey", "dGVzdHNhbHQ", KeyGeneration::V2)),
            "fdff82620ba4a596c31b1bbacb24d761d67950113f423b2a3dfab87a91fd1196",
        );
        assert_eq!(
            hex(&derive_user_key(
                "klipgard-second-master-key-fedcba9876543210",
                "Zml4ZWQtc2FsdC1mb3ItdGhlLWtub3duLXZlY3Rvcg",
                KeyGeneration::V2,
            )),
            "611cfcc3d72613b48ab23f9a4a470585f1db1cb1b29f55f983a0675edf6b6aa6",
        );
    }

    ///story: [DATA-146] Generacja wynika tylko z nazwy bucketu: pusta lista (domyślnie) to zawsze generacja 1, czyli zero zmian dla istniejących danych.
    #[test]
    fn the_bucket_name_picks_the_generation() {
        let none: Vec<String> = vec![];
        assert_eq!(key_generation_for_bucket("recordings", &none), KeyGeneration::V1);
        let listed = vec!["new-recordings".to_string(), "new-thumbs".to_string()];
        assert_eq!(key_generation_for_bucket("new-recordings", &listed), KeyGeneration::V2);
        assert_eq!(key_generation_for_bucket("recordings", &listed), KeyGeneration::V1);
        assert_eq!(key_generation_for_bucket("new-recordings-old", &listed), KeyGeneration::V1);
    }

    ///story: [DATA-146] Generacja 2 bierze własny master key, gdy jest ustawiony, a bez niego — dotychczasowy. Generacja 1 zawsze bierze dotychczasowy.
    #[test]
    fn generation_2_falls_back_to_the_first_master_key() {
        assert_eq!(master_key_for_generation(KeyGeneration::V1, "m1", Some("m2")), "m1");
        assert_eq!(master_key_for_generation(KeyGeneration::V2, "m1", Some("m2")), "m2");
        assert_eq!(master_key_for_generation(KeyGeneration::V2, "m1", Some("")), "m1");
        assert_eq!(master_key_for_generation(KeyGeneration::V2, "m1", None), "m1");
    }

    ///story: Generacja 2 daje inny klucz niż generacja 1 przy tym samym master key i soli — obiekt skopiowany do nowego bucketu jest naprawdę przeszyfrowany.
    #[test]
    fn generation_2_differs_from_generation_1() {
        let a = derive_user_key("masterkey", "c2FsdDE", KeyGeneration::V1);
        let b = derive_user_key("masterkey", "c2FsdDE", KeyGeneration::V2);
        assert_ne!(a, b);
    }

    ///story: Każdy użytkownik ma unikalny klucz SSE-C dzięki różnym saltom — nagrania jednego klienta pozostają niedostępne dla drugiego, nawet przy wspólnym master key.
    #[test]
    fn test_different_salts_different_keys() {
        let key1 = derive_user_key("masterkey", "c2FsdDE", KeyGeneration::V1);
        let key2 = derive_user_key("masterkey", "c2FsdDI", KeyGeneration::V1);
        assert_ne!(key1, key2, "Different salts must produce different keys");
    }

    ///story: Nagłówki SSE-C (algorytm, klucz base64, MD5 klucza) mają dokładnie ten format, którego oczekuje S3 — upload nagrań kamer nie zostanie odrzucony przez bucket.
    #[test]
    fn test_ssec_headers_format() {
        let key = derive_user_key("testkey", "dGVzdHNhbHQ", KeyGeneration::V1);
        let (algo, key_b64, md5_b64) = ssec_headers(&key);
        assert_eq!(algo, "AES256");
        assert!(!key_b64.is_empty());
        assert!(!md5_b64.is_empty());
        // Key base64 should decode to 32 bytes
        use base64::engine::general_purpose::STANDARD;
        let decoded = STANDARD.decode(&key_b64).unwrap();
        assert_eq!(decoded.len(), 32);
    }
}
